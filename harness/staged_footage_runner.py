# ---------------------------------------------------------------------------
# Synthetic frame generation
# ---------------------------------------------------------------------------

def _make_realistic_frame(
    width: int = 640,
    height: int = 480,
    luminance: float = 1.0,   # 1.0 = normal, 0.3 = low-light
    seed: int = 0,
) -> np.ndarray:
    """
    Generate a synthetic frame that is NOT all black.
    Realistic camera sensor noise with a simple horizon line and gradient sky.
    luminance < 0.4 → triggers preprocessor (low-light threshold).
    """
    rng = np.random.default_rng(seed)

    # Gradient sky
    frame = np.zeros((height, width, 3), dtype=np.float32)
    for row in range(height):
        intensity = max(0, 1.0 - row / height * 0.7)
        frame[row, :] = intensity * 120

    # Horizon line
    horizon = int(height * 0.6)
    frame[horizon:, :] = np.array([60, 80, 40], dtype=np.float32)

    # Add sensor noise
    noise = rng.normal(0, 8, frame.shape).astype(np.float32)
    frame = np.clip(frame + noise, 0, 255)

    # Apply luminance
    frame = (frame * luminance).clip(0, 255).astype(np.uint8)
    return frame


# ---------------------------------------------------------------------------
# Synthetic detection sequence (MockDetector replacement for staged run)
# ---------------------------------------------------------------------------

@dataclass
class StagedDetection:
    frame_idx:   int
    track_id:    str
    bbox:        List[float]   # [x1, y1, x2, y2] normalised
    entity_type: str           # "human", "animal", etc.
    confidence:  float


def _generate_person_approaching_fence(
    n_frames: int = 60,
    jitter_sigma: float = 0.012,
    include_animal: bool = True,
    seed: int = 42,
) -> List[StagedDetection]:
    """
    Synthetic detection sequence: person starts long-range, moves to close-range,
    then "climbs" (bbox moves upward). Used to test the full trigger pipeline.

    jitter_sigma: Standard deviation of Gaussian noise on bbox coords.
    0.012 ≈ 1.2% of frame width — realistic for a stabilised RTSP stream.
    This is the key test of whether IoU thresholds set on clean synthetic
    fixtures hold against real-world bbox jitter.
    """
    rng    = random.Random(seed)
    events = []

    # Person trajectory: starts small (long-range), grows larger (close-range)
    for i in range(n_frames):
        progress = i / max(n_frames - 1, 1)   # 0.0 → 1.0

        # Person approaches: bbox grows from 0.08 to 0.22 height
        bbox_h = 0.08 + progress * 0.14
        bbox_w = bbox_h * 0.45

        # Horizontal position: drifts toward center
        cx = 0.70 - progress * 0.20
        cy = 0.60 - progress * 0.08   # moves upward slightly (climbing)

        x1 = cx - bbox_w / 2
        y1 = cy - bbox_h / 2
        x2 = cx + bbox_w / 2
        y2 = cy + bbox_h / 2

        # Gaussian jitter on all coords
        def jitter(v: float) -> float:
            return float(np.clip(v + rng.gauss(0, jitter_sigma), 0.01, 0.99))

        bbox = [jitter(x1), jitter(y1), jitter(x2), jitter(y2)]

        # Ensure x1 < x2, y1 < y2 after jitter
        if bbox[0] >= bbox[2]:
            bbox[0], bbox[2] = bbox[2] - 0.01, bbox[0] + 0.01
        if bbox[1] >= bbox[3]:
            bbox[1], bbox[3] = bbox[3] - 0.01, bbox[1] + 0.01

        events.append(StagedDetection(
            frame_idx   = i,
            track_id    = "trk_person_01",
            bbox        = bbox,
            entity_type = "human",
            confidence  = 0.82 + rng.gauss(0, 0.04),  # realistic conf jitter
        ))

    # Add one animal detection at frame 20 (should be filtered, not trigger)
    if include_animal:
        events.append(StagedDetection(
            frame_idx   = 20,
            track_id    = "trk_deer_01",
            bbox        = [0.10, 0.55, 0.22, 0.72],
            entity_type = "animal",
            confidence  = 0.71,
        ))

    return sorted(events, key=lambda d: d.frame_idx)


# ---------------------------------------------------------------------------
# Divergence record
# ---------------------------------------------------------------------------

@dataclass
class DivergenceRecord:
    frame_idx:   int
    component:   str
    expected:    str
    observed:    str
    threshold:   Optional[float] = None
    recommendation: str = ""


# ---------------------------------------------------------------------------
# Pipeline run result
# ---------------------------------------------------------------------------

@dataclass
class PipelineRunResult:
    total_frames:         int        = 0
    frames_processed:     int        = 0
    frames_skipped:       int        = 0
    events_published:     int        = 0
    trigger_confirmed:    int        = 0
    trigger_critical:     int        = 0
    animal_detected:      int        = 0
    motion_detected:      int        = 0
    preprocessor_engaged: int        = 0
    divergences:          List[DivergenceRecord] = field(default_factory=list)
    iou_samples:          List[float] = field(default_factory=list)
    confirmation_frames_at_trigger: Optional[int] = None
    run_duration_s:       float      = 0.0

    def to_text(self) -> str:
        sep = "=" * 60
        lines = [
            sep,
            "PHASE ZURICH — PART 2: STAGED FOOTAGE RUN RESULTS",
            sep,
            f"  Total frames in clip     : {self.total_frames}",
            f"  Frames processed         : {self.frames_processed}",
            f"  Frames skipped (MSE dedup): {self.frames_skipped}",
            f"  Events published         : {self.events_published}",
            "",
            "EVENT BREAKDOWN",
            f"  motion_detected          : {self.motion_detected}",
            f"  animal_detected          : {self.animal_detected}",
            f"  trigger (confirmed)      : {self.trigger_confirmed}",
            f"  trigger (critical)       : {self.trigger_critical}",
            "",
            f"  Preprocessor engaged     : {self.preprocessor_engaged} frame(s)",
            "",
        ]

        if self.iou_samples:
            avg_iou = sum(self.iou_samples) / len(self.iou_samples)
            min_iou = min(self.iou_samples)
            lines += [
                "BBOX CONSISTENCY (IoU Stats with jitter)",
                f"  Samples                  : {len(self.iou_samples)}",
                f"  Mean IoU                 : {avg_iou:.3f}",
                f"  Min  IoU                 : {min_iou:.3f}",
                f"  Threshold                : 0.350",
                f"  Threshold margin         : {min_iou - 0.350:.3f} "
                  + ("✓ SAFE" if min_iou > 0.35 else "⚠ BREACHED"),
                "",
            ]

        if self.confirmation_frames_at_trigger is not None:
            lines += [
                "TRIGGER CONFIRMATION",
                f"  Frames at first confirm  : {self.confirmation_frames_at_trigger}",
                f"  Expected                 : 3",
                f"  {'✓ Correct' if self.confirmation_frames_at_trigger == 3 else '⚠ DIVERGENCE — see below'}",
                "",
            ]

        if self.divergences:
            lines += ["DIVERGENCES (must be investigated, NOT silently retuned):"]
            for d in self.divergences:
                lines += [
                    f"  Frame {d.frame_idx:03d} | {d.component}",
                    f"    Expected : {d.expected}",
                    f"    Observed : {d.observed}",
                    f"    Action   : {d.recommendation}",
                ]
        else:
            lines.append("DIVERGENCES: None ✓")

        lines.append(sep)
        lines.append(f"  Run completed in {self.run_duration_s:.2f}s")
        lines.append(sep)
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# StagedFootageRunner
# ---------------------------------------------------------------------------

class StagedFootageRunner:
    """
    Runs the full Model A pipeline on synthetic or real footage.

    When using real footage (video_path given), reads frames via OpenCV.
    When using synthetic footage, generates frames + detections internally.

    Uses MockDetector (or real YOLO if use_yolo=True and weights exist).
    """

    def __init__(
        self,
        video_path:    Optional[str] = None,
        use_yolo:      bool          = False,
        jitter_sigma:  float         = 0.012,
        n_frames:      int           = 60,
        trigger_type_at_frame: int   = 30,   # inject climbing trigger after frame 30
    ) -> None:
        self._video_path   = video_path
        self._use_yolo     = use_yolo
        self._jitter_sigma = jitter_sigma
        self._n_frames     = n_frames
        self._trigger_at   = trigger_type_at_frame

    def run(self) -> PipelineRunResult:
        """Execute the full pipeline run and return results."""
        from model_a.animal_filter import AnimalFilter
        from model_a.bbox_consistency import BBoxConsistencyChecker
        from model_a.preprocessor import Preprocessor
        from model_a.schema_v1 import EntityType, EventType, Severity, TriggerType
        from model_a.trigger_detector import TriggerDetector

        result = PipelineRunResult()
        t_start = time.monotonic()

        pre     = Preprocessor()
        afilt   = AnimalFilter()
        checker = BBoxConsistencyChecker(iou_threshold=0.35)
        trigger = TriggerDetector(confirmation_frames=3)

        # Generate synthetic detections indexed by frame
        staged_dets = _generate_person_approaching_fence(
            n_frames     = self._n_frames,
            jitter_sigma = self._jitter_sigma,
        )
        dets_by_frame: dict[int, list[StagedDetection]] = {}
        for d in staged_dets:
            dets_by_frame.setdefault(d.frame_idx, []).append(d)

        result.total_frames = self._n_frames
        ts = datetime.datetime.now(datetime.timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%S.%f"
        )[:-3] + "Z"

        prev_iou_bbox: Optional[List[float]] = None
        confirmed_frame_idx: Optional[int]   = None

        for frame_idx in range(self._n_frames):
            # Generate frame (or read from video)
            luminance = 0.25 if frame_idx in {15, 16, 17} else 1.0
            frame = _make_realistic_frame(
                luminance=luminance,
                seed=frame_idx,
            )

            # Preprocessor — engages on dark frames
            is_dark_before = frame.mean() < 50
            enhanced = pre.enhance(frame)
            is_dark_after  = enhanced.mean() < 50
            if is_dark_before:
                result.preprocessor_engaged += 1
                logger.debug("Frame %d: low-light detected, preprocessor engaged.", frame_idx)

            # Get detections for this frame
            frame_dets = dets_by_frame.get(frame_idx, [])
            if not frame_dets:
                result.frames_skipped += 1
                # Miss any active tracks
                trigger.miss("trk_person_01")
                prev_iou_bbox = None
                continue

            result.frames_processed += 1

            for det in frame_dets:
                etype = EntityType(det.entity_type) if det.entity_type in [e.value for e in EntityType] else EntityType.unknown

                # Animal filter
                from model_a.detector import Detection
                d_obj = Detection(
                    track_id    = det.track_id,
                    entity_type = etype,
                    confidence  = det.confidence,
                    bbox        = det.bbox,
                    class_id    = 0,
                    class_name  = det.entity_type,
                    frame_number = frame_idx,
                )
                animals, candidates = afilt.classify([d_obj])

                if animals:
                    result.animal_detected += len(animals)
                    result.events_published += len(animals)

                for cdet in candidates:
                    # Motion event
                    result.motion_detected += 1
                    result.events_published += 1

                    if cdet.track_id is None:
                        continue

                    # BBox IoU check — record IoU for divergence analysis
                    if prev_iou_bbox is not None and cdet.track_id == "trk_person_01":
                        iou = checker._compute_iou(prev_iou_bbox, cdet.bbox)
                        result.iou_samples.append(iou)

                        if iou < 0.35:
                            result.divergences.append(DivergenceRecord(
                                frame_idx   = frame_idx,
                                component   = "BBoxConsistencyChecker",
                                expected    = "IoU >= 0.35 (threshold from synthetic tests)",
                                observed    = f"IoU = {iou:.3f} (jitter={self._jitter_sigma})",
                                threshold   = 0.35,
                                recommendation=(
                                    "Real footage has higher jitter than synthetic fixtures. "
                                    "If IoU < 0.35 occurs for a real person walking normally, "
                                    "consider lowering threshold to 0.25 AFTER verifying that "
                                    "shadow/foliage false-positives still fail at new threshold. "
                                    "DO NOT retune silently — requires explicit owner approval."
                                ),
                            ))

                    prev_iou_bbox = cdet.bbox

                    # Trigger detection (only after frame 30 — "fence line reached")
                    if frame_idx >= self._trigger_at:
                        consistent = checker.check(cdet.track_id, cdet.bbox)
                        if not consistent:
                            trigger.miss(cdet.track_id)
                            continue

                        result_t = trigger.update(
                            cdet.track_id, TriggerType.climbing, frame_idx
                        )

                        if result_t.should_publish:
                            result.events_published += 1
                            if result_t.severity == Severity.confirmed:
                                result.trigger_confirmed += 1
                                if confirmed_frame_idx is None:
                                    confirmed_frame_idx  = frame_idx
                                    result.confirmation_frames_at_trigger = (
                                        result_t.confirmation_frames
                                    )
                                    # Verify Rule #1
                                    if result_t.confirmation_frames != 3:
                                        result.divergences.append(DivergenceRecord(
                                            frame_idx   = frame_idx,
                                            component   = "TriggerDetector",
                                            expected    = "confirmation_frames == 3",
                                            observed    = f"confirmation_frames == {result_t.confirmation_frames}",
                                            recommendation="Investigate TriggerDetector state machine. Rule #1 violation.",
                                        ))
                            elif result_t.severity == Severity.critical:
                                result.trigger_critical += 1

        result.run_duration_s = time.monotonic() - t_start
        return result


