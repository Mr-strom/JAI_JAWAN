"""
Staged Footage Runner — Phase Zurich Part 2
SIH26187 | Phase Zurich

PURPOSE
  Runs the FULL Model A pipeline (frame_pipeline.py) against either:
    a) A real video clip (path provided via --video CLI arg)
    b) A synthetic staged clip (generated by this module when no real clip given)

  The goal is to verify that components tuned on synthetic test fixtures
  (bbox_consistency.py's IoU=0.35 threshold, trigger_detector.py's 3-frame rule)
  hold against real/realistic footage with natural jitter.

REAL FOOTAGE NOTE
  If you have actual CCTV footage, pass it via:
    python harness/staged_footage_runner.py --video path/to/clip.mp4

  The pipeline uses MockDetector unless --use-yolo is passed AND yolov8n.pt exists.
  Honest limitation: YOLOv8n weights (yolov8n.pt) must be downloaded separately
  (ultralytics.com). If not present, MockDetector is used with a realistic
  "person approaching fence" detection sequence.

SYNTHETIC STAGED CLIP
  When no real footage is available, generates 60 frames (2s at 30fps equivalent):
  - Realistic noise background (not black — simulates camera sensor noise)
  - A "person" represented as a moving bbox that:
      * Starts long_range (small bbox, bottom-right)
      * Moves close_range (bbox grows, center-frame)
      * "Climbs" (bbox moves upward in final frames)
  - With gaussian jitter on all bbox coordinates to test IoU threshold robustness
  - One sequence of 3 "low-light" frames (darker) to test preprocessor

WHAT IS VERIFIED
  1. 3-frame confirmation rule holds with real/jittery bboxes
  2. No animal misclassification on the specific footage used
  3. Preprocessor engages correctly for dark frames
  4. Any divergence from synthetic test expectations is LOGGED (not silently retuned)
"""

